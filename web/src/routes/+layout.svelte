<script>
  import { ui, restoreLang, setLang } from '$lib/state.svelte.js';
  import { page } from '$app/state';
  import { strings } from '$lib/i18n.js';
  import { onMount } from 'svelte';
  let { children } = $props();
  const t = $derived(strings[ui.lang]);
  const onSubmitPage = $derived(page.url?.pathname?.startsWith('/submit'));
  // The dashboard runs edge to edge; every other page is a reading column.
  const bleed = $derived(page.url?.pathname === '/');

  // The NiCE mechanism: the bar is quiet until you scroll, then it earns its
  // line and shadow. Nothing here is decorative. A bar that is always solid
  // steals 60px from a full-screen map, and a bar that is never solid becomes
  // unreadable the moment content passes under it.
  let scrolled = $state(false);
  onMount(() => {
    const onScroll = () => { scrolled = window.scrollY > 8; };
    onScroll();
    window.addEventListener('scroll', onScroll, { passive: true });
    return () => window.removeEventListener('scroll', onScroll);
  });

  // If the published data was generated by the demo seeder, say so on every
  // page. Synthetic numbers that look official are worse than no numbers.
  // 'demo' synthetic numbers · 'beta' real but empty · 'live' real reports.
  // An empty map with no explanation is indistinguishable from a broken one,
  // so beta gets its own banner rather than silence.
  let mode = $state(null);
  const demo = $derived(mode === 'demo');
  onMount(async () => {
    restoreLang();
    try {
      const m = await (await fetch('/data/meta.json')).json();
      mode = m.mode ?? (m.demo ? 'demo' : 'live');
    } catch { /* meta is optional */ }
  });

  // The document language has to follow the toggle. It was hardcoded to "bn",
  // so a screen reader read the English pages with a Bangla voice, and
  // translation tools were told the wrong thing.
  $effect(() => {
    if (typeof document !== 'undefined') document.documentElement.lang = ui.lang;
  });
</script>

