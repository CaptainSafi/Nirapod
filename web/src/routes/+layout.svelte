      {#if onSubmitPage}
        <a class="report ghost" href="/">{t.nav_map}</a>
      {:else}
        <a class="report" href="/submit/">{t.nav_submit}</a>
      {/if}
    </div>
  </div>
</header>

{#if mode === 'demo'}
  <div class="demo">
